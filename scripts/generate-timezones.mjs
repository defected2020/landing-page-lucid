// One-off generator for components/globe/timezones.js: the coordinates of
// each IANA time zone's principal city, from the tz database's zone.tab.
//   node scripts/generate-timezones.mjs /usr/share/zoneinfo/zone.tab > components/globe/timezones.js

import fs from 'node:fs';

const src = process.argv[2] || '/usr/share/zoneinfo/zone.tab';

// ISO 6709 "+DDMM[SS]" / "+DDDMM[SS]" to decimal degrees
const parse = (s, degDigits) => {
  const sign = s[0] === '-' ? -1 : 1;
  const d = +s.slice(1, 1 + degDigits);
  const m = +s.slice(1 + degDigits, 3 + degDigits);
  const sec = +(s.slice(3 + degDigits) || 0);
  return sign * (d + m / 60 + sec / 3600);
};

const zones = {};
for (const line of fs.readFileSync(src, 'utf8').split('\n')) {
  if (!line || line.startsWith('#')) continue;
  const [, coords, name] = line.split('\t');
  const m = coords.match(/^([+-]\d+)([+-]\d+)$/);
  const lat = parse(m[1], 2);
  const lon = parse(m[2], 3);
  zones[name] = `${Math.round(lat * 10) / 10},${Math.round(lon * 10) / 10}`;
}

const body = Object.entries(zones)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([k, v]) => `${k}:${v}`)
  .join(';');

process.stdout.write(`// Generated by scripts/generate-timezones.mjs from the tz database's zone.tab.
// "Zone/Name:lat,lon" pairs: the principal city of each IANA time zone.
export const ZONES = '${body}';
`);
